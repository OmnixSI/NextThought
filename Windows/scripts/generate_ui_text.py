#!/usr/bin/env python3
"""Generate Windows/src/NextThought.Core/UiTextMac.g.cs from the Mac string catalogue.

Source: Resources/Localization/Localizable.xcstrings (read-only). Every source string is
emitted with its English translation, including format placeholders and plural variants;
formatting is left to the caller, exactly like the Mac app.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "Resources" / "Localization" / "Localizable.xcstrings"
TARGET = ROOT / "Windows" / "src" / "NextThought.Core" / "UiTextMac.g.cs"


def csharp(value: str) -> str:
    out = []
    for char in value:
        code = ord(char)
        if char == "\\":
            out.append("\\\\")
        elif char == '"':
            out.append('\\"')
        elif char == "\n":
            out.append("\\n")
        elif char == "\r":
            out.append("\\r")
        elif char == "\t":
            out.append("\\t")
        elif code < 0x20 or code == 0x7F:
            out.append(f"\\u{code:04X}")
        else:
            out.append(char)
    return "".join(out)


def english(localization: dict) -> str | None:
    if not localization:
        return None
    if isinstance(localization.get("stringUnit"), dict):
        value = localization["stringUnit"].get("value")
        if isinstance(value, str):
            return value
    variations = localization.get("variations")
    if isinstance(variations, dict):
        # Plural variants: the "other" form is the default template on both platforms.
        for category in ("plural", "device"):
            forms = variations.get(category)
            if isinstance(forms, dict):
                for key in ("other", "one"):
                    unit = forms.get(key)
                    if isinstance(unit, dict) and isinstance(unit.get("stringUnit"), dict):
                        value = unit["stringUnit"].get("value")
                        if isinstance(value, str):
                            return value
    return None


def main() -> int:
    catalogue = json.loads(SOURCE.read_text(encoding="utf-8"))
    strings = catalogue.get("strings", {})
    rows: list[tuple[str, str]] = []
    missing: list[str] = []
    for key, entry in strings.items():
        value = english((entry.get("localizations") or {}).get("en") or {})
        if value is None:
            missing.append(key)
            continue
        rows.append((key, value))
    rows.sort(key=lambda pair: pair[0])
    lines = [
        "// <auto-generated> from Resources/Localization/Localizable.xcstrings (en); do not edit. </auto-generated>",
        f"// strings: {len(rows)}",
        "namespace NextThought.Core;",
        "",
        "internal static class UiTextMacEnglish",
        "{",
        f"    public const int Count = {len(rows)};",
        "",
        "    public static readonly IReadOnlyDictionary<string, string> Strings = new Dictionary<string, string>(StringComparer.Ordinal)",
        "    {",
    ]
    for key, value in rows:
        lines.append(f'        ["{csharp(key)}"] = "{csharp(value)}",')
    lines += ["    };", "}", ""]
    TARGET.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {TARGET} ({len(rows)} strings)")
    for key in missing:
        print("skip (no English):", key)
    return 0


if __name__ == "__main__":
    sys.exit(main())
